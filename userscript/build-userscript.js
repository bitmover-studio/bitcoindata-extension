#!/usr/bin/env node
'use strict';

/**
 * Builds a single-file userscript (Greasy Fork / Tampermonkey / Violentmonkey / Greasemonkey)
 * from the extension's forum features:
 *   - components/balance-api.js  blockchain + price lookups (uses GM_xmlhttpRequest when available)
 *   - components/buttons.js      post editor BBCode toolbar
 *   - components/forum-hover.js  address / transaction hover cards
 *
 * The popup, sidebar, background alarms, notifications and context menus depend on
 * WebExtension APIs, so they are not part of the userscript.
 *
 * Usage:  node userscript/build-userscript.js
 * Output: userscript/bitcoindata.user.js
 */

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const outFile = path.join(__dirname, 'bitcoindata.user.js');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));

const meta = [
  ['name', 'bitcoindata extension'],
  ['namespace', 'https://bitcoindata.science'],
  ['version', manifest.version],
  ['description', 'Hover Bitcoin addresses and transactions on Bitcointalk & AltcoinsTalks for live balance and transaction details, and insert dynamic BBCode price, balance and fee images in the post editor.'],
  ['author', 'bitmover'],
  ['license', 'MIT'],
  ['homepageURL', 'https://bitcoindata.science/browser-extension'],
  ['supportURL', 'https://bitcointalk.org/index.php?topic=5485996.msg63701109#msg63701109'],
  ['icon', 'https://bitcoindata.science/favicon.ico'],
  ['match', '*://bitcointalk.org/*'],
  ['match', '*://*.altcoinstalks.com/*'],
  ['grant', 'GM_xmlhttpRequest'],
  ['grant', 'GM.xmlHttpRequest'],
  ['connect', 'bitcoindata.science'],
  ['connect', 'mempool.space'],
  ['connect', 'api.blockcypher.com'],
  ['run-at', 'document-idle'],
  ['noframes', ''],
];

const sources = [
  'components/balance-api.js',
  'components/buttons.js',
  'components/forum-hover.js',
];

const keyWidth = Math.max(...meta.map(([key]) => key.length)) + 1;
const header = [
  '// ==UserScript==',
  ...meta.map(([key, value]) => `// @${key.padEnd(keyWidth)}${value}`.trimEnd()),
  '// ==/UserScript==',
].join('\n');

const body = sources.map(file => {
  const code = fs.readFileSync(path.join(root, file), 'utf8')
    .replace(/\r\n/g, '\n')
    // A single 'use strict' directive is emitted at the top of the wrapper instead.
    .replace(/^\s*['"]use strict['"];?[ \t]*\n/m, '')
    .trim();
  const title = `// ─── ${file} `;
  return `${title.padEnd(80, '─')}\n${code}`;
}).join('\n\n');

const output = `${header}

/*
 * bitcoindata extension - userscript build
 * https://bitcoindata.science/browser-extension
 *
 * Generated by userscript/build-userscript.js from the extension sources. Do not edit by hand:
 * change the files in components/ and run \`node userscript/build-userscript.js\` again.
 *
 * MIT License - Copyright (c) 2024-2026 bitmover
 */

(() => {
'use strict';

// Tells the shared sources they are running as a userscript (no WebExtension APIs).
const BDS_USERSCRIPT = true;

${body}
})();
`;

fs.writeFileSync(outFile, output);
console.log(`Built ${path.relative(root, outFile)} (v${manifest.version}, ${(Buffer.byteLength(output) / 1024).toFixed(1)} KB)`);
